"""Data-assimilation evaluation: observing-system simulation experiment (OSSE).

A "truth" trajectory is generated by the full model under a known event. A
digital twin starts at homeostatic baseline WITHOUT knowing the event and
receives noisy observations of a small clinically-observable subset of states
at intervals. The mechanistic network should carry those corrections into
unobserved states as well — that propagation of observational information is
the property a mechanistic twin offers over statistical state estimation.

Arms:
  truth        full model with the event (ground truth)
  blind        twin: no event, no assimilation (worst case)
  twin_assim   twin: no event + sequential state updates at obs times
  twin_fcst    twin: assimilate only t<=120, evaluate forecast error t>120

Metrics: RMSE vs truth over observed / latent / all body modules.

Usage: python benchmark/assimilation_eval.py [-o benchmark/assimilation_report.json]
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import numpy as np  # noqa: E402
from backend.contracts import Interpretation, Intervention, RunSettings  # noqa: E402
from backend.simulation import simulate  # noqa: E402
from backend.body_library import MODULES  # noqa: E402

HORIZON = 240
OBS_EVERY = 30          # min between observation updates
GAIN = 0.15             # continuous nudging rate (1/min)
NOISE_SD = 0.03         # observation noise (dimensionless deviation units)
FORECAST_CUT = 120      # twin_fcst assimilates only up to this time

# Clinically observable subset: sympathetic/vital tone, volume status (CVP/
# ultrasound proxy), serum osmolality axis, renal output and filtration,
# plasma sodium, ventilation.
OBSERVED = ["sympathetic", "plasma_vol", "osmotic_drive", "urine_output",
            "gfr", "sodium_load", "ventilation", "preload"]
# Latent states reported separately: the RAAS/ADH axis is what observation
# must recover indirectly through network coupling.
LATENT = ["renin", "angiotensin", "aldosterone", "adh", "aqp2",
          "kaliuresis", "thirst", "edema"]


def run(channels, observations=None):
    iv = Intervention(kind="other", label="clinical event", entity=None,
                      duration_min=120, body_channels=channels)
    return simulate(Interpretation(title="osse", interventions=[iv]),
                    RunSettings(horizon_min=HORIZON), {},
                    observations=observations)


def rmse(truth, test, mids, times, test_times, t_min=0, t_max=None):
    """Root-mean-square error of `test` traces vs `truth` over the module set.

    `test` is interpolated onto the truth time grid first (each arm can carry
    different integration boundaries)."""
    mask = (times >= t_min) & (times <= (t_max if t_max is not None else times[-1]))
    errs = []
    for m in mids:
        key = "body:" + m
        if key not in truth or key not in test:
            continue
        t_arr = np.asarray(truth[key])[mask]
        e_arr = np.interp(times[mask], test_times, np.asarray(test[key]))
        errs.append(((t_arr - e_arr) ** 2).mean())
    return float(np.mean(errs) ** 0.5) if errs else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", default=str(ROOT / "benchmark" / "assimilation_report.json"))
    args = ap.parse_args()

    rng = np.random.default_rng(7)
    truth = run(["hemorrhage"])
    blind = run([])
    times = np.asarray(truth["time"], dtype=float)

    module_ids = [m["id"] for m in MODULES if "body:" + m["id"] in truth["traces"]]
    observed = [m for m in OBSERVED if "body:" + m in truth["traces"]]
    latent = [m for m in LATENT if "body:" + m in truth["traces"]]

    # Sample noisy observations of the observable states at every OBS_EVERY.
    obs_times = np.arange(OBS_EVERY, HORIZON + 1, OBS_EVERY)
    observations = []
    for t in obs_times:
        k = int(np.searchsorted(times, t))
        for m in observed:
            val = float(truth["traces"]["body:" + m][k]) + rng.normal(0, NOISE_SD)
            observations.append({"time_min": float(t), "state": "body:" + m,
                                 "value": val, "gain": GAIN, "mode": "nudge"})
    fcst_obs = [o for o in observations if o["time_min"] <= FORECAST_CUT]
    # Forecast arm: assimilate through the cut, then release the nudges so the
    # twin forecasts freely from its assimilated state.
    fcst_obs += [{"time_min": float(FORECAST_CUT) + 0.01, "state": "body:" + m,
                  "value": 0.0, "gain": 0.0, "mode": "nudge"} for m in observed]

    twin = run([], observations)
    twin_fcst = run([], fcst_obs)

    report = {
        "protocol": {
            "design": "observing-system simulation experiment (OSSE): truth generated by the model, twin starts at baseline without knowing the event",
            "event": "hemorrhage (120 min)",
            "horizon_min": HORIZON,
            "obs_every_min": OBS_EVERY,
            "update_gain": GAIN,
            "noise_sd": NOISE_SD,
            "n_observations": len(observations),
            "forecast_cut_min": FORECAST_CUT,
            "observed_modules": observed,
            "latent_modules": latent,
        },
        "arms": {
            "blind": {
                "rmse_observed": rmse(truth["traces"], blind["traces"], observed, times, np.asarray(blind["time"],dtype=float)),
                "rmse_latent": rmse(truth["traces"], blind["traces"], latent, times, np.asarray(blind["time"],dtype=float)),
                "rmse_all": rmse(truth["traces"], blind["traces"], module_ids, times, np.asarray(blind["time"],dtype=float)),
            },
            "twin_assim": {
                "rmse_observed": rmse(truth["traces"], twin["traces"], observed, times, np.asarray(twin["time"],dtype=float)),
                "rmse_latent": rmse(truth["traces"], twin["traces"], latent, times, np.asarray(twin["time"],dtype=float)),
                "rmse_all": rmse(truth["traces"], twin["traces"], module_ids, times, np.asarray(twin["time"],dtype=float)),
            },
            "twin_fcst_t>120": {
                "rmse_observed": rmse(truth["traces"], twin_fcst["traces"], observed, times, np.asarray(twin_fcst["time"],dtype=float), t_min=FORECAST_CUT),
                "rmse_latent": rmse(truth["traces"], twin_fcst["traces"], latent, times, np.asarray(twin_fcst["time"],dtype=float), t_min=FORECAST_CUT),
                "rmse_all": rmse(truth["traces"], twin_fcst["traces"], module_ids, times, np.asarray(twin_fcst["time"],dtype=float), t_min=FORECAST_CUT),
            },
            "blind_t>120": {
                "rmse_observed": rmse(truth["traces"], blind["traces"], observed, times, np.asarray(blind["time"],dtype=float), t_min=FORECAST_CUT),
                "rmse_latent": rmse(truth["traces"], blind["traces"], latent, times, np.asarray(blind["time"],dtype=float), t_min=FORECAST_CUT),
                "rmse_all": rmse(truth["traces"], blind["traces"], module_ids, times, np.asarray(blind["time"],dtype=float), t_min=FORECAST_CUT),
            },
        },
    }
    # Trajectories for the figure: one observed and two latent modules.
    show_obs, show_lat = "urine_output", ["adh", "renin"]
    report["trajectories"] = {
        "times": times[::8].tolist(),
        "obs_times": obs_times.tolist(),
        "modules": {},
    }
    for m in [show_obs, *show_lat]:
        key = "body:" + m
        interp = lambda res: np.interp(times[::8], np.asarray(res["time"], dtype=float), np.asarray(res["traces"][key])).round(4).tolist()
        report["trajectories"]["modules"][m] = {
            "truth": interp(truth), "blind": interp(blind), "twin": interp(twin),
            "twin_fcst": interp(twin_fcst), "observed": m in observed,
        }

    # Per-module improvement table for the latent set (the headline result).
    report["latent_detail"] = []
    for m in latent:
        b = rmse(truth["traces"], blind["traces"], [m], times, np.asarray(blind["time"],dtype=float))
        a = rmse(truth["traces"], twin["traces"], [m], times, np.asarray(twin["time"],dtype=float))
        peak = float(np.abs(np.asarray(truth["traces"]["body:" + m])).max())
        report["latent_detail"].append({"module": m, "truth_peak": round(peak, 4),
                                        "rmse_blind": round(b, 4), "rmse_assim": round(a, 4)})
    Path(args.o).write_text(json.dumps(report, indent=2))
    print(json.dumps(report["arms"], indent=2))
    print("latent detail:", json.dumps(report["latent_detail"], indent=1))


if __name__ == "__main__":
    main()
